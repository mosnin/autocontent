"""Parsing-layer port fidelity for the SEO auditor.

Every expectation here was generated by running the TypeScript original
(`ai-seo-audit/lib/audit.ts`) over the same input and recording what it
produced, so these are parity assertions against the source of truth rather
than a snapshot of whatever the Python happens to do today.

The parsing layer is where a regex port diverges silently: JS `RegExp` and
Python `re` disagree about `$`, about Unicode classes, and about how
alternation interacts with `findall` capture groups. The cases below target
exactly those seams.
"""
from __future__ import annotations

