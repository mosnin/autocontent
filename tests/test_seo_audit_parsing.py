@pytest.mark.parametrize(
    ("html", "markdown", "base", "expected"),
    [
        (
            '<a href="/a">x</a><a href="https://other.example/b">y</a>',
            "",
            "https://acme.example/p/",
            ["https://acme.example/a", "https://other.example/b"],
        ),
        # Non-web schemes are dropped.
        (
            '<a href="mailto:x@y.com">m</a><a href="tel:+1">t</a>'
            '<a href="javascript:void(0)">j</a>',
            "",
            "https://acme.example/",
            [],
        ),
        # Fragments are stripped, which also collapses "#" to the base URL.
        ('<a href="/a#frag">x</a>', "", "https://acme.example/", ["https://acme.example/a"]),
        (
            '<a href="">empty</a><a href="#">hash</a>',
            "",
            "https://acme.example/",
            ["https://acme.example/"],
        ),
        # Duplicates collapse, insertion order is preserved.
        ('<a href="/dup">1</a><a href="/dup">2</a>', "", "https://acme.example/",
         ["https://acme.example/dup"]),
        # Markdown link syntax contributes too.
        (
            "",
            "[link](https://md.example/x) and [two](https://md.example/y)",
            "https://acme.example/",
            ["https://md.example/x", "https://md.example/y"],
        ),
        # `data-href` is not a link.
        ('<a data-href="/decoy">no</a>', "", "https://acme.example/", []),
        # Default ports are dropped, matching `new URL().toString()`.
        (
            '<a href="https://acme.example:443/ssl">p</a>',
            "",
            "https://acme.example/",
            ["https://acme.example/ssl"],
        ),
        # A bare origin serializes with a trailing slash.
        ('<a href="https://acme.example">bare</a>', "", "https://acme.example/",
         ["https://acme.example/"]),
        # Protocol-relative hrefs inherit the base scheme.
        ('<a href="//cdn.example/x">p</a>', "", "https://acme.example/",
         ["https://cdn.example/x"]),
        # Query-only hrefs resolve against the base path.
        ('<a href="?q=1">rel</a>', "", "https://acme.example/page",
         ["https://acme.example/page?q=1"]),
    ],
)
def test_extract_links(html, markdown, base, expected):
    assert parsing.extract_links(html, markdown, base) == expected


def test_url_origin_ignores_case_and_path():
    assert parsing.url_origin("HTTPS://Acme.Example/deep/path?q=1") == "https://acme.example"


