# Attribute reading: the `href` vs `data-href` boundary
# ---------------------------------------------------------------------------


@pytest.mark.parametrize(
    ("tag", "attr", "expected"),
    [
        # The whole point of the leading-boundary assertion: `data-href` must
        # not satisfy a request for `href`.
        ('<a data-href="/decoy" href="/real">', "href", "/real"),
        ('<a data-href="/decoy">', "href", None),
        ('<a xhref="/no">', "href", None),
        ('<link data-rel="canonical" rel="canonical" href="/c">', "rel", "canonical"),
        # Quoting and spacing variants the source accepts.
        ("<a href='/single'>", "href", "/single"),
        ("<a href=/unquoted class=x>", "href", "/unquoted"),
        ('<a HREF="/upper">', "href", "/upper"),
        ('<a href = "/spaced">', "href", "/spaced"),
        # Attribute values ARE entity-decoded (unlike script bodies).
        ('<a href="/q?a=1&amp;b=2">', "href", "/q?a=1&b=2"),
    ],
)
def test_get_attr_requires_an_attribute_boundary(tag, attr, expected):
    assert parsing.get_attr(tag, attr) == expected


