    html = (
        '<script type="application/ld+json">{"a":1}</script>'
        '<script type="application/ld+json">bad</script>'
    )
    result = parsing.extract_json_ld(html)
    assert (len(result.schemas), result.block_count, result.parse_failures) == (1, 2, 1)


