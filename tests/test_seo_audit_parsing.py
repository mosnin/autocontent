def test_extract_json_ld_counts_blocks_and_failures(body, schemas, blocks_found, failures):
    html = f'<script type="application/ld+json">{body}</script>'
    result = parsing.extract_json_ld(html)
    assert len(result.schemas) == schemas
    assert result.block_count == blocks_found
    assert result.parse_failures == failures


